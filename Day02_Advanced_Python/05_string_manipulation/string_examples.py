username = "  Abinaya Selvam  "

# Remove extra spaces
print(username.strip())

# Convert to uppercase
print(username.upper())

# Convert to lowercase
print(username.lower())

# Replace text
print(username.replace("Selvam", "S"))

# Split string
full_name = "Abinaya Selvam"
print(full_name.split(" "))

# Check whether text exists
print("Abinaya" in full_name)